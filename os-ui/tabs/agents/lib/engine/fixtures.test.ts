import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSystem } from '@tabs/agents/lib/system-schema';
import { fixtureSpecs, hasWhenGuard, SCRIPT_ID, type EngineFixture } from '@tabs/agents/lib/engine/parity-harness';

const DIR = fileURLToPath(new URL('./fixtures/', import.meta.url));
const specs = fixtureSpecs();

test('the fixture set covers every shipped template, the software team and the three shapes', () => {
  const names = specs.map((s) => s.name);
  for (const key of ['blank', 'analyze', 'evaluate', 'recommend']) assert.ok(names.includes(`template-${key}`), `template-${key}`);
  for (const key of ['blank', 'analyst', 'recommender', 'reviewer', 'researcher']) assert.ok(names.includes(`agent-template-${key}`), `agent-template-${key}`);
  for (const n of ['software-team', 'shape-single-read', 'shape-supervisor-two-members', 'shape-guarded-handoff-held-write']) assert.ok(names.includes(n), n);
  assert.equal(new Set(names).size, names.length, 'fixture names are unique');
});

for (const spec of specs) {
  test(`fixture ${spec.name} is present, frozen under ${SCRIPT_ID}, and well-formed`, () => {
    const file = join(DIR, `${spec.name}.json`);
    assert.ok(existsSync(file), `missing ${file} — the fixtures are frozen; a lost one must be restored from git, never regenerated`);
    const fx = JSON.parse(readFileSync(file, 'utf8')) as EngineFixture;
    assert.equal(fx.version, 1);
    assert.equal(fx.name, spec.name);
    assert.equal(fx.script, SCRIPT_ID, 'fixture was recorded under the current script rules');
    // The yaml is the one the spec still ships: a template edit must be a visible fixture change.
    assert.equal(fx.yaml, spec.yaml, 'the fixture yaml matches the shipped system.yaml it was recorded from');
    assert.equal(fx.guarded, hasWhenGuard(parseSystem(fx.yaml)), '`guarded` matches the yaml');
    assert.ok(fx.transcript.exchanges.length > 0, 'the recorded model transcript is not empty');
    assert.ok(fx.golden.path.length > 0, 'the golden visited at least one node');
    assert.ok(fx.golden.finalText.length > 0, 'the golden has a final text');
    for (const call of fx.golden.toolCalls) {
      assert.ok(fx.golden.path.includes(call.node), `tool call on an unvisited node: ${call.node}`);
      assert.ok(['ok', 'held', 'error'].includes(call.outcome), `unknown outcome ${call.outcome}`);
    }
  });
}

test('no orphan fixture file (every JSON under ./fixtures has a spec)', () => {
  const files = readdirSync(DIR).filter((f) => f.endsWith('.json')).map((f) => f.replace(/\.json$/, ''));
  const names = new Set(specs.map((s) => s.name));
  assert.deepEqual(files.filter((f) => !names.has(f)), []);
});

test('the guarded fixture still records the DEFECT the walker had (the reason it is frozen)', () => {
  const fx = JSON.parse(readFileSync(join(DIR, 'shape-guarded-handoff-held-write.json'), 'utf8')) as EngineFixture;
  assert.equal(fx.guarded, true);
  assert.ok(fx.golden.path.includes('publisher'), 'the walker ignored `when` and visited the guarded target');
  assert.equal(fx.golden.held, 1, 'and held the write that target attempted');
});
