/** OS system ids are minted by the store (`sys_…`); anything else never reaches a generated comment. */
export const SYSTEM_ID_RE = /^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/;

/** The 00 §4 header. Its only variable part is the validated system id: no user text in code. */
function header(id: string, what: string): string {
  if (!SYSTEM_ID_RE.test(id)) throw new AgentModuleError(`system id ${JSON.stringify(id)} is not a plain identifier`);
  return [
    `// GENERATED by os-ui agent-module@${AGENT_MODULE_FORMAT} from agent-system/${id}. Do not edit; edit the source.`,
    `// ${what}`,
  ].join('\n');
}

const GRAPH_BODY = String.raw`
/** Last write wins. */
const last = (_prev, next) => next;
/** 'add_messages'-style channels other than 'messages': append. */
const append = (prev, next) => (prev ?? []).concat(next ?? []);
const DEFAULTS = { boolean: () => false, number: () => 0, string: () => '', add_messages: () => [] };

/** The team state: the transcript, every declared channel, and the agent visits so far. */
const spec = { ...MessagesAnnotation.spec, steps: Annotation({ reducer: (a, b) => a + b, default: () => 0 }) };
for (const [name, type] of Object.entries(TEAM.channels)) {
  spec[name] = Annotation({ reducer: type === 'add_messages' ? append : last, default: DEFAULTS[type] ?? (() => null) });
}
export const TeamState = Annotation.Root(spec);

// The guard semantics: empty values are false; values compare as strings, objects never equal.
function truthy(v) {
  if (v === undefined || v === null || v === false || v === '' || v === 0) return false;
  return Array.isArray(v) ? v.length > 0 : true;
}
function same(a, b) {
  if (a === b) return true;
  if (a === null || b === null || a === undefined || b === undefined) return false;
  if (typeof a === 'object' || typeof b === 'object') return false;
  return String(a) === String(b);
}
function ch(s, name) {
  return Object.prototype.hasOwnProperty.call(TEAM.channels, name) ? s[name] : undefined;
}

const TYPE_OK = { boolean: (v) => typeof v === 'boolean', number: (v) => typeof v === 'number', string: (v) => typeof v === 'string' };

/** The built-in tool an agent uses to set a team state channel its hand-off guard reads. */
function setStateTool(channels) {
  return tool(
    async ({ channel, value }) => {
      if (!channels.includes(channel)) return JSON.stringify({ error: 'unknown_channel', channel, allowed: channels });
      const type = TEAM.channels[channel];
      if (TYPE_OK[type] && !TYPE_OK[type](value)) return JSON.stringify({ error: 'wrong_type', channel, expected: type });
      return JSON.stringify({ set: channel, value });
    },
    {
      name: 'set_state',
      description: 'Set one of the team state channels (' + channels.join(', ') + '). The hand-off after your turn reads them.',
      schema: { type: 'object', properties: { channel: { type: 'string', enum: channels }, value: {} }, required: ['channel', 'value'] },
    },
  );
}

/** The channel writes an agent turn made through 'set_state', in order (the last one wins). */
function writesOf(messages) {
  const out = {};
  for (const m of messages) {
    if (m.type !== 'tool' || m.name !== 'set_state') continue;
    try {
      const r = JSON.parse(String(m.content));
      if (r && typeof r.set === 'string' && !r.error) out[r.set] = TEAM.channels[r.set] === 'add_messages' ? [r.value] : r.value;
    } catch {
      // not a write
    }
  }
  return out;
}

const prompt = (file) => readFileSync(new URL('./prompts/' + file, import.meta.url), 'utf8').trimEnd();

function systemPromptOf(agent) {
  const base = prompt(agent.id + '.md') + (agent.memory ? '\n\n' + prompt(agent.id + '.memory.md') : '');
  if (!agent.sets.length) return base;
  return base + '\n\nWhen your part is done, record it with the set_state tool. Channels you may set: ' +
    agent.sets.map((c) => c + ' (' + TEAM.channels[c] + ')').join(', ') + '.';
}

const ROUTE_TOOL = (members) => ({
  type: 'function',
  function: {
    name: 'route',
    description: 'Choose which team member works next, or END when the task is done.',
    parameters: { type: 'object', properties: { next: { type: 'string', enum: [...members, 'END'] }, brief: { type: 'string' } }, required: ['next'] },
  },
});

/**
 * Build the team graph.
 * @param {object} opts
 * @param {object | ((agent: object) => object)} opts.model a LangChain chat model, or one per agent
 * @param {Record<string, object> | object[]} opts.tools an implementation for every name in TOOL_NAMES
 * @param {object[] | ((agent: object) => object[])} [opts.middleware] 'createAgent' middleware
 * @param {object} [opts.checkpointer] a LangGraph checkpointer (MemorySaver, PostgresSaver, …)
 * @param {number} [opts.maxSteps] agent visits before the run ends (default 12)
 */
export function buildGraph({ model, tools, middleware = [], checkpointer, maxSteps = 12 } = {}) {
  const byName = Array.isArray(tools) ? Object.fromEntries(tools.map((t) => [t.name, t])) : { ...(tools ?? {}) };
  const missing = TOOL_NAMES.filter((n) => !byName[n]);
  if (missing.length) throw new Error('buildGraph: no implementation for tool(s): ' + missing.join(', '));
  if (!model) throw new Error('buildGraph: a chat model is required');
  const modelOf = (a) => (typeof model === 'function' ? model(a) : model);
  const middlewareOf = (a) => (typeof middleware === 'function' ? middleware(a) : middleware);
  const supervisorOf = (id) => TEAM.agents.find((s) => s.members.includes(id));
  const targets = [END, ...TEAM.agents.flatMap((a) => ['agent_' + a.id, 'route_' + a.id])];

  const graph = new StateGraph(TeamState);
  for (const a of TEAM.agents) {
    const own = a.tools.map((n) => byName[n]);
    if (a.sets.length) own.push(setStateTool(a.sets));
    const agent = createAgent({ name: a.id, model: modelOf(a), tools: own, systemPrompt: systemPromptOf(a), middleware: middlewareOf(a), version: 'v2' });

    graph.addNode('agent_' + a.id, async (state, config) => {
      const out = await agent.invoke({ messages: state.messages }, config);
      // What this visit added, by message id: the agent's own context management (a summary that
      // replaced older turns in ITS window) never rewrites the team transcript.
      const known = new Set(state.messages.map((m) => m.id));
      const added = out.messages.filter((m) => !known.has(m.id));
      return { messages: added, steps: 1, ...writesOf(added) };
    });

    graph.addNode('route_' + a.id, async (state) => {
      if (state.steps >= maxSteps) return new Command({ goto: END });
      for (const [i, h] of TEAM.handoffs.entries()) {
        if (h.from === a.id && GUARDS[i](state)) return new Command({ goto: 'agent_' + h.to });
      }
      if (a.members.length) {
        const ai = await modelOf(a)
          .bindTools([ROUTE_TOOL(a.members)], { tool_choice: { type: 'function', function: { name: 'route' } } })
          .invoke([new SystemMessage('You supervise ' + a.members.join(', ') + '. Call route with who works next, or END when the task is done.'), ...state.messages]);
        const call = (ai.tool_calls ?? []).find((c) => c.name === 'route');
        const next = call?.args?.next;
        if (!a.members.includes(next)) return new Command({ goto: END });
        const brief = String(call.args.brief ?? '').trim();
        return new Command({ goto: 'agent_' + next, update: { messages: [new HumanMessage({ content: '[' + a.id + ' -> ' + next + '] ' + brief, name: a.id })] } });
      }
      const sup = supervisorOf(a.id);
      return new Command({ goto: sup ? 'route_' + sup.id : END });
    }, { ends: targets });

    graph.addEdge('agent_' + a.id, 'route_' + a.id);
  }
  graph.addEdge(START, 'agent_' + TEAM.entrypoint);
  return graph.compile({ checkpointer });
}
`;

function renderGraph(input: AgentModuleInput, team: ModuleTeam, toolNames: string[]): string {
  const guards = team.handoffs.map((h) => `  ${compileGuard(h.when)},`);
  return [
    header(input.id, 'A LangGraph JS StateGraph with one createAgent per agent; the team is TEAM below. Run it: see README.md.'),
    "import { readFileSync } from 'node:fs';",
    "import { Annotation, Command, END, MessagesAnnotation, START, StateGraph } from '@langchain/langgraph';",
    "import { createAgent, HumanMessage, SystemMessage, tool } from 'langchain';",
    '',
    '/** The team as data: agents, their tools and supervisees, the hand-offs and the state channels. */',
    `export const TEAM = ${JSON.stringify(team, null, 2)};`,
    '',
    '/** The tool interface: every tool the agents call. `buildGraph({ tools })` must implement each. */',
    `export const TOOL_NAMES = ${JSON.stringify(toolNames)};`,
    '',
    '/** One guard per TEAM.handoffs entry, in order. */',
    'const GUARDS = [',
    ...guards,
    '];',
    GRAPH_BODY,
  ].join('\n');
}

