/** The topology the module encodes, from the compiled IR. Deterministic. */
export function moduleTeam(sys: System, ir: IR, disabled: readonly string[] = []): ModuleTeam {
  const off = new Set(disabled);
  if (off.has(ir.entrypoint)) throw new AgentModuleError(`the entrypoint agent '${ir.entrypoint}' is disabled`);
  const channels: Record<string, string> = {};
  for (const k of Object.keys(ir.channels).sort()) if (k !== 'messages') channels[k] = ir.channels[k];
  const handoffs = ir.commands
    .filter((c) => !off.has(c.from) && !off.has(c.to))
    .map((c) => ({ from: c.from, to: c.to, when: c.when && c.when.trim() && !isLegacyUnguardedWhen(c.when) ? c.when.trim() : null }));
  const writers = new Set(handoffs.filter((h) => h.when !== null).map((h) => h.from));
  const writable = Object.keys(channels);
  const agents = ir.nodes
    .filter((n) => !off.has(n.id))
    .map((n) => ({
      id: n.id,
      model: n.model,
      // The names the agent really calls: aliases resolved, discovery companions added — the same
      // rule `grantedToolSpecs` applies for the OS run.
      tools: [...new Set(withDiscoveryCompanions(n.tools.map(resolveAlias)))].sort(),
      members: n.members.filter((m) => !off.has(m)),
      sets: writers.has(n.id) ? writable : [],
      // `prompts/<id>.memory.md` exists (the agent's durable notes, appended to its prompt).
      memory: (n.memory ?? '').trim().length > 0,
    }));
  return { name: sys.system.name, entrypoint: ir.entrypoint, agents, handoffs, channels };
}

/** Every tool name the graph calls, sorted — the tool interface the caller implements. */
export function moduleToolNames(team: ModuleTeam): string[] {
  const names = [...new Set(team.agents.flatMap((a) => a.tools))].sort();
  const bad = names.filter((n) => !TOOL_NAME_RE.test(n));
  if (bad.length) throw new AgentModuleError(`tool name(s) ${JSON.stringify(bad)} are not plain identifiers`);
  return names;
}

/** The generated graph's own tools (written literally in `graph.mjs` below; a test pins the two together). */
export const MODULE_SET_STATE_TOOL = 'set_state';
export const MODULE_ROUTE_TOOL = 'route';

/**
 * The module graph's OWN tool names a run of this team can send to the model, besides the governed
 * ones: `set_state` for an agent whose hand-off guard reads a channel, `route` for a supervisor.
 */
export function moduleEngineToolNames(team: ModuleTeam): string[] {
  const out: string[] = [];
  if (team.agents.some((a) => a.sets.length > 0)) out.push(MODULE_SET_STATE_TOOL);
  if (team.agents.some((a) => a.members.length > 0)) out.push(MODULE_ROUTE_TOOL);
  return out;
}

// ---------------------------------------------------------------- guards ---

function guardExpr(ast: WhenAst): string {
  switch (ast.kind) {
    case 'literal': return JSON.stringify(ast.value);
    case 'channel': return `ch(s, ${JSON.stringify(ast.name)})`;
    case 'eq': return `${ast.op === '==' ? '' : '!'}same(${guardExpr(ast.left)}, ${guardExpr(ast.right)})`;
    case 'and': return `(truthy(${guardExpr(ast.left)}) && truthy(${guardExpr(ast.right)}))`;
    case 'or': return `(truthy(${guardExpr(ast.left)}) || truthy(${guardExpr(ast.right)}))`;
  }
}

/** A `when` guard as a JS arrow over the graph state, with `engine/when.ts`'s exact semantics. */
export function compileGuard(when: string | null): string {
  if (when === null) return '() => true';
  return `(s) => truthy(${guardExpr(parseWhen(when))})`;
}

