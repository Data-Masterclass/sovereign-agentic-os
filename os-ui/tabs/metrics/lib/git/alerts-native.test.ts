import { test } from 'node:test';
import assert from 'node:assert/strict';
import { load } from 'js-yaml';
import { dbtMetricsByMember, generateAlertFiles, readAlertFiles, alertOwnerToken, AlertFileError } from '@tabs/metrics/lib/git/alerts-native';
import type { AlertRuleRecord } from '@tabs/metrics/lib/alert-store';
import { VIEW, committedDbt } from '@tabs/metrics/lib/git/alerts-fixtures';

function repo(): Map<string, string> {
  return committedDbt();
}

const V = VIEW;
const rule = (over: Partial<AlertRuleRecord> = {}): AlertRuleRecord => ({
  id: 'alert_rev_low', member: `${V}.revenue`, comparator: 'lt', threshold: 100, notify: ['in_app'],
  owner: 'amir@acme.example', domain: 'sales', createdAt: '2026-11-20T10:00:00.000Z', ...over,
});

test('the committed dbt metrics resolve OS members to dbt metric names', () => {
  const m = dbtMetricsByMember(repo());
  assert.equal(m.get(`${V}.revenue`), 'revenue');
  assert.equal(m.get(`${V}.orders`), 'orders');
});

test('an alert is a dbt saved query on the dbt metric, the threshold only in config.meta.os_alert', () => {
  const { files, pending } = generateAlertFiles('sales', [rule()], repo());
  assert.deepEqual(pending, []);
  assert.deepEqual([...files.keys()], ['metrics/alerts/alert_rev_low.yml']);
  const doc = load(files.get('metrics/alerts/alert_rev_low.yml')!) as Record<string, unknown>;
  assert.deepEqual(Object.keys(doc).sort(), ['saved_queries', 'version']);
  assert.deepEqual(doc.saved_queries, [{
    name: 'alert_rev_low',
    label: `Alert: ${V}.revenue lt 100`,
    description: `Sovereign OS alert alert_rev_low: notify when the metric revenue is lt 100. Run it with \`mf query --saved-query alert_rev_low\`.`,
    query_params: { metrics: ['revenue'] },
    config: { meta: { os_alert: { id: 'alert_rev_low', comparator: 'lt', threshold: 100, owner: alertOwnerToken('amir@acme.example'), notify: ['in_app'] } } },
  }]);
  assert.match(files.get('metrics/alerts/alert_rev_low.yml')!, /^# Generated by Sovereign OS/);
});

test('the owner is the opaque repository token (same formula as the agents and dashboards writers)', () => {
  assert.match(alertOwnerToken('amir@acme.example'), /^[0-9a-f]{12}$/);
  assert.notEqual(alertOwnerToken('amir@acme.example'), alertOwnerToken('bea@acme.example'));
});

test('NEGATIVE TWIN: a rule whose metric has no committed dbt metric is pending, never a broken saved query', () => {
  const { files, pending } = generateAlertFiles('sales', [rule({ id: 'a2', member: `${V}.margin` })], repo());
  assert.equal(files.size, 0);
  assert.equal(pending.length, 1);
  assert.match(pending[0].reason, /no dbt metric/);
});

test('only the domain\'s own rules are written; output is byte-stable and sorted', () => {
  const rules = [rule({ id: 'b_rule' }), rule({ id: 'a_rule', comparator: 'gte', threshold: 5 }), rule({ id: 'x_other', domain: 'finance' })];
  const a = generateAlertFiles('sales', rules, repo()).files;
  const b = generateAlertFiles('sales', [...rules].reverse(), repo()).files;
  assert.deepEqual([...a.entries()], [...b.entries()]);
  assert.deepEqual([...a.keys()], ['metrics/alerts/a_rule.yml', 'metrics/alerts/b_rule.yml']);
});

test('the reader is the inverse of the writer', () => {
  const { files } = generateAlertFiles('sales', [rule(), rule({ id: 'a_rule', comparator: 'gte', threshold: 5.5, member: `${V}.orders` })], repo());
  assert.deepEqual(readAlertFiles(files), [
    { path: 'metrics/alerts/a_rule.yml', id: 'a_rule', savedQuery: 'a_rule', metric: 'orders', comparator: 'gte', threshold: 5.5, ownerToken: alertOwnerToken('amir@acme.example') },
    { path: 'metrics/alerts/alert_rev_low.yml', id: 'alert_rev_low', savedQuery: 'alert_rev_low', metric: 'revenue', comparator: 'lt', threshold: 100, ownerToken: alertOwnerToken('amir@acme.example') },
  ]);
});

test('NEGATIVE TWIN: the reader refuses a file without a threshold, with two metrics, or with an unknown comparator', () => {
  const ok = generateAlertFiles('sales', [rule()], repo()).files.get('metrics/alerts/alert_rev_low.yml')!;
  for (const broken of [ok.replace(/threshold: 100\n/, ''), ok.replace(/- revenue\n/, '- revenue\n        - orders\n'), ok.replace(/comparator: lt/, 'comparator: approx')]) {
    assert.throws(() => readAlertFiles(new Map([['metrics/alerts/alert_rev_low.yml', broken]])), AlertFileError);
  }
});
