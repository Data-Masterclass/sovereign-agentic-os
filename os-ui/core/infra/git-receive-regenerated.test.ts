import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import * as git from 'isomorphic-git';
import { beginReceive, regeneratedPaths, abortReceive, __clearRepoKinds, registerRepoKind, type Pusher, type RepoKind } from '@core/infra/git-receive';
import { commitTree, ensureV2Repo, commitSubtree, MAIN } from '@core/infra/git-store';
import { layoutMarker, LAYOUT_MARKER_PATH, LAYOUT_V2, userRepoName } from '@core/infra/repo-layout';
import { GENERATED_MARK } from '@core/infra/repo-readme';

const creator: Pusher = { id: 'amir', role: 'creator', domains: ['sales'] };
const builder: Pusher = { id: 'bea', role: 'builder', domains: ['sales'] };
const writer = { name: 'Writer', email: 'writer@os.invalid' };
const added = (p: string, content = 'x\n') => ({ path: p, status: 'added' as const, content });
const dbtKind: RepoKind = {
  kind: 'd',
  root: 'dbt',
  matches: (p) => p.startsWith('models/'),
  validate: () => null,
  ingest: async () => ({ kind: 'd', created: 0, updated: 0, skipped: 0, notes: [] }),
};

test('regenerated paths: generated READMEs, a user repo\'s agents/, un-ingested files under the v2 generated folders', () => {
  const tracked = [LAYOUT_MARKER_PATH, 'README.md', 'data/dbt/dbt_project.yml', 'agents/a/system.yaml', 'data/dbt/README.md'];
  const base = { tracked, layout: LAYOUT_V2, repo: 'domain-sales', oldGenerated: (p: string) => p === 'README.md', kinds: [dbtKind] };
  const r = (changed: ReturnType<typeof added>[], repoKind: 'domain' | 'user' = 'domain') => regeneratedPaths({ ...base, changed, repoKind }).map((x) => x.path);
  assert.deepEqual(r([added('README.md', `${GENERATED_MARK}\n# tweaked\n`)]), ['README.md'], 'a generated README edited with its mark on');
  assert.deepEqual(r([added('README.md', '# mine\n')]), [], 'without the mark it becomes the writer\'s and is kept');
  assert.deepEqual(r([{ path: 'README.md', status: 'deleted', content: null } as never]), ['README.md'], 'deleting it only brings it back');
  // The dbt project's README is not a generated-layout README, but the dbt generator rewrites it.
  assert.deepEqual(r([added('data/dbt/README.md', '# mine\n')]), ['data/dbt/README.md'], 'the dbt generator rewrites its README');
  assert.deepEqual(r([added('apps/x/README.md', '# mine\n')]), [], 'an app folder (pushable source) is not regenerated');
  assert.deepEqual(r([added('data/dbt/models/gold/x.sql')]), [], 'a file a kind ingests');
  assert.deepEqual(r([added('data/dbt/notes.txt')]), ['data/dbt/notes.txt'], 'a file nothing ingests would be overwritten');
  assert.deepEqual(r([added('agents/a/system.yaml')], 'user'), ['agents/a/system.yaml']);
  assert.deepEqual(r([added('notes/todo.md')], 'user'), [], 'a folder the OS does not regenerate stays the owner\'s');
  assert.deepEqual(regeneratedPaths({ ...base, layout: 1, changed: [added('notes.txt')], repoKind: 'domain' }), [], 'v1 keeps its rules');
});

test('the gate refuses a push to a regenerated path with the reason (v2 domain repo and user repo)', async () => {
  __clearRepoKinds();
  registerRepoKind(dbtKind);
  const reposDir = fs.mkdtempSync(path.join(os.tmpdir(), 'wp55-regen-'));
  const head = await commitTree('sales', new Map([[LAYOUT_MARKER_PATH, layoutMarker()], ['data/dbt/dbt_project.yml', 'name: s\n']]), { author: writer, message: 'v2', reposDir });
  const { blob } = await git.readBlob({ fs, gitdir: path.join(reposDir, 'sales.git'), oid: head.sha, filepath: 'README.md' });
  assert.ok(Buffer.from(blob).toString('utf8').startsWith(GENERATED_MARK));
  const upd = [{ ref: MAIN, oldSha: head.sha, newSha: 'f'.repeat(40), fastForward: true }];
  const d1 = await beginReceive({ domain: 'sales', pusher: builder, updates: upd, changed: [{ path: 'README.md', status: 'modified', content: `${GENERATED_MARK}\n# tweaked\n` }] }, { reposDir });
  assert.equal(d1.ok, false);
  assert.match(d1.ok === false ? d1.message : '', /generated README and is regenerated by the OS/);
  const d2 = await beginReceive({ domain: 'sales', pusher: builder, updates: upd, changed: [added('data/dbt/models/gold/gold_x.sql', 'select 1\n')] }, { reposDir });
  assert.equal(d2.ok, true, d2.ok ? '' : d2.message);
  abortReceive('sales');

  const repo = userRepoName('amir');
  await ensureV2Repo(repo, { reposDir });
  const u = await commitSubtree(repo, 'agents/', new Map([['agents/a/system.yaml', 'name: a\n']]), { author: writer, message: 'a', reposDir });
  const d3 = await beginReceive(
    { domain: repo, pusher: creator, updates: [{ ref: MAIN, oldSha: u.sha, newSha: 'e'.repeat(40), fastForward: true }], changed: [{ path: 'agents/a/system.yaml', status: 'modified', content: 'name: b\n' }] },
    { reposDir },
  );
  assert.equal(d3.ok, false);
  assert.match(d3.ok === false ? d3.message : '', /regenerated by the OS on every commit/);
  __clearRepoKinds();
});
