"""Generate the run-pod block of values.dagster-run-identity.yaml from values.dagster-launcher-lockdown.yaml.

    python3 scripts/gen-dagster-run-identity.py            # print the block
    python3 scripts/gen-dagster-run-identity.py --write    # rewrite it between the markers in the overlay

With the launcher lock-down the code location stops propagating its container context and the run
pod's settings live in the launcher's own `run_k8s_config`
(`dagster.runLauncher.config.customRunLauncher.config.run_k8s_config`). WP-15 adds to that run pod:
ServiceAccount `dagster-run`, no automounted token, a projected token for os-ui, the runner's Trino
password file, the chart CA and four env entries. Helm REPLACES lists, so the overlay has to restate
the lists it extends (env, volume mounts, volumes) in full. They are derived here from the lock-down
overlay instead of being copied by hand, so a change to the lock-down's lists reaches the run pod; the
overlay's test fails CI on any difference from this output.
"""
from __future__ import annotations

import argparse
import copy
import os
import sys

import yaml

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
LOCK = os.path.join(ROOT, "values.dagster-launcher-lockdown.yaml")
OVERLAY = os.path.join(ROOT, "values.dagster-run-identity.yaml")
BEGIN = "# >>> generated by scripts/gen-dagster-run-identity.py (do not edit by hand; --write regenerates)\n"
END = "# <<< end generated\n"

RUN_SA = "dagster-run"
VOLUMES = [
    {"name": "os-ui-token", "projected": {"sources": [{"serviceAccountToken": {"audience": "os-ui", "expirationSeconds": 3600, "path": "token"}}]}},
    {"name": "dagster-runner-trino", "secret": {"secretName": "trino-service-users", "items": [{"key": "svc-dagster-runner", "path": "password"}]}},
    {"name": "trino-ca", "secret": {"secretName": "trino-tls", "items": [{"key": "ca.crt", "path": "ca.crt"}]}},
]
MOUNTS = [
    {"name": "os-ui-token", "mountPath": "/var/run/secrets/os-ui", "readOnly": True},
    {"name": "dagster-runner-trino", "mountPath": "/var/run/secrets/dagster-runner-trino", "readOnly": True},
    {"name": "trino-ca", "mountPath": "/var/run/secrets/trino-ca", "readOnly": True},
]
ENV = [
    {"name": "TRINO_TLS_PORT", "value": "8443"},
    {"name": "TRINO_RUNNER_USER", "value": "svc-dagster-runner"},
    {"name": "TRINO_CA_FILE", "value": "/var/run/secrets/trino-ca/ca.crt"},
    {"name": "OS_UI_URL", "value": "http://os-ui:3000"},
]


def run_block(lock: dict) -> dict:
    rk = lock["dagster"]["runLauncher"]["config"]["customRunLauncher"]["config"]["run_k8s_config"]
    names = lambda xs: {x["name"] for x in xs}  # noqa: E731
    for extra, have in ((VOLUMES, rk["pod_spec_config"]["volumes"]), (MOUNTS, rk["container_config"]["volume_mounts"]), (ENV, rk["container_config"]["env"])):
        clash = names(extra) & names(have)
        if clash:
            raise SystemExit(f"the lock-down overlay already defines {sorted(clash)}")
    return {
        "runLauncher": {"config": {"customRunLauncher": {"config": {"run_k8s_config": {
            "container_config": {
                "env": copy.deepcopy(rk["container_config"]["env"]) + ENV,
                "volume_mounts": copy.deepcopy(rk["container_config"]["volume_mounts"]) + MOUNTS,
            },
            "pod_spec_config": {
                "service_account_name": RUN_SA,
                "automount_service_account_token": False,
                "volumes": copy.deepcopy(rk["pod_spec_config"]["volumes"]) + VOLUMES,
            },
        }}}}}
    }


def block_text() -> str:
    lock = yaml.safe_load(open(LOCK))
    # the `runLauncher:` key of the overlay's own `dagster:` mapping, indented to sit under it
    body = yaml.safe_dump(run_block(lock), sort_keys=False, width=100, default_flow_style=False)
    return BEGIN + "".join("  " + ln if ln.strip() else ln for ln in body.splitlines(True)) + END


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    text = block_text()
    if not a.write:
        sys.stdout.write(text)
        return 0
    s = open(OVERLAY).read()
    i, j = s.index(BEGIN), s.index(END) + len(END)
    open(OVERLAY, "w").write(s[:i] + text + s[j:])
    return 0


if __name__ == "__main__":
    sys.exit(main())
