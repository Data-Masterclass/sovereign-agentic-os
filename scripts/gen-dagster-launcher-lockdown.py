"""Generate values.dagster-launcher-lockdown.yaml from charts/sovereign-agentic-os/values.yaml.

    python3 scripts/gen-dagster-launcher-lockdown.py                      # the default profile (stdout)
    python3 scripts/gen-dagster-launcher-lockdown.py --profile values.stackit-managed.yaml
    python3 scripts/gen-dagster-launcher-lockdown.py --write              # rewrite the checked-in file

Why a generator: with the lock-down the code location stops propagating its container context
(`includeConfigInLaunchedRuns: false`) and the SAME pod settings move into the run launcher's own
`run_k8s_config`. Helm replaces a list instead of merging it, so the overlay has to restate the
code location's whole `sovereign` entry and the run pod's lists. Hand-copying them let the image pin
and the env drift from values.yaml. Now the copy is DERIVED: the image pin, env, resources, volumes
and the repo-sync sidecar come from values.yaml's `sovereign` deployment, and
scripts/tests/dagster-launcher-lockdown.test.sh fails CI when the checked-in file differs from this
output, and judges the render with dagster-k8s's own code (dagster_launcher_lockdown.py).

--profile FILE (repeatable) merges a deploy profile over values.yaml the way Helm does (maps merge,
lists are replaced), so a profile that changes the deployment or sets run-pod pull secrets
(`dagster.runLauncher.config.k8sRunLauncher.imagePullSecrets`, values.dev.yaml, values.stackit-managed.yaml)
gets an overlay that matches it.
"""
from __future__ import annotations

import argparse
import copy
import os
import sys

import yaml

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
VALUES = os.path.join(ROOT, "charts", "sovereign-agentic-os", "values.yaml")
OUT = os.path.join(ROOT, "values.dagster-launcher-lockdown.yaml")
RELEASE = "agentic-os"
NAMESPACE = "agentic-os"
LOCATION = "sovereign"

HEADER = """\
# SPDX-License-Identifier: Apache-2.0
# Copyright 2026 Borek Data Ventures UG
#
# GENERATED by scripts/gen-dagster-launcher-lockdown.py from charts/sovereign-agentic-os/values.yaml.
# Do not edit by hand: change values.yaml's `sovereign` deployment, then regenerate with --write.
# scripts/tests/dagster-launcher-lockdown.test.sh fails CI when this file differs from the generator.
#
# Dagster run-launcher lock-down (opt-in overlay). Apply on top of the profile you deploy:
#   helm upgrade --install agentic-os charts/sovereign-agentic-os -n agentic-os -f <profile> -f values.dagster-launcher-lockdown.yaml
# A profile that sets run-pod pull secrets (values.dev.yaml, values.stackit-managed.yaml) needs the file
# generated for it: scripts/gen-dagster-launcher-lockdown.py --profile <profile> > <file>.
# Rollback: drop this file from the deploy.
#
# With Dagster's documented options only (docs/components/dagster.md, "Run launcher lock-down";
# https://docs.dagster.io/deployment/oss/deployment-options/kubernetes/customizing-your-deployment):
#   - the run launcher is still dagster_k8s.K8sRunLauncher, configured through the subchart's
#     `CustomRunLauncher` type, because the subchart's own K8sRunLauncher template cannot render the
#     two allow-list keys;
#   - `only_allow_user_defined_k8s_config_fields: {{}}` and `only_allow_user_defined_env_vars: []`: a run's
#     `dagster-k8s/config` tag may set NOTHING (no env, no resources, no image, no volumes). The OS sends
#     no such tag: the run worker reads its pinned commit and principal from the run's own tags
#     (`os/pinned`, `os/principal`; images/extensions/dagster/repo.py);
#   - dagster-k8s applies the allow-list to the CODE LOCATION's container context too, so the code
#     location stops propagating it (`includeConfigInLaunchedRuns.enabled: false`) and the run pod's
#     env, volumes, sidecar, service account and resources move, unchanged, into the launcher's own
#     `run_k8s_config` (operator-defined, not subject to the allow-list).
# Another overlay that adds operator run settings (values.dagster-run-identity.yaml) goes under
# `customRunLauncher.config.run_k8s_config` and restates the lists it extends (Helm replaces lists);
# `k8sRunLauncher.runK8sConfig` is not read while this overlay is applied.
"""


def merge(a, b):
    """Helm's values merge: maps recurse, everything else (lists included) is replaced."""
    if isinstance(a, dict) and isinstance(b, dict):
        out = dict(a)
        for k, v in b.items():
            out[k] = merge(a[k], v) if k in a else copy.deepcopy(v)
        return out
    return copy.deepcopy(b)


def load_values(profiles: list[str], values: str = VALUES) -> dict:
    v = yaml.safe_load(open(values))
    for p in profiles:
        v = merge(v, yaml.safe_load(open(p)) or {})
    return v


def generate(profiles: list[str] | None = None, values: str = VALUES) -> str:
    v = load_values(profiles or [], values)
    dg = v["dagster"]
    dep = next(d for d in dg["dagster-user-deployments"]["deployments"] if d["name"] == LOCATION)
    stock = ((dg.get("runLauncher") or {}).get("config") or {}).get("k8sRunLauncher") or {}
    labels = (((stock.get("runK8sConfig") or {}).get("podTemplateSpecMetadata") or {}).get("labels")) or {}

    container = {
        "image_pull_policy": dep["image"]["pullPolicy"],
        "env_from": [{"config_map_ref": {"name": f"{RELEASE}-dagster-user-deployments-{LOCATION}-user-env"}}],
        "env": dep["env"],
        "resources": dep["resources"],
        "volume_mounts": dep["volumeMounts"],
    }
    pod = {
        "service_account_name": f"{RELEASE}-dagster-user-deployments-user-deployments",
        "automount_service_account_token": True,
        "volumes": dep["volumes"],
        "containers": dep["sidecarContainers"],
    }
    if dg["dagster-user-deployments"].get("imagePullSecrets"):  # the code location propagates them
        pod["image_pull_secrets"] = dg["dagster-user-deployments"]["imagePullSecrets"]
    cfg = {
        # the stock render (charts/dagster _run-launcher.tpl, K8sRunLauncher), unchanged
        "load_incluster_config": True,
        "job_namespace": NAMESPACE,
        "image_pull_policy": "Always",
        "service_account_name": f"{RELEASE}-dagster",
        "dagster_home": "/opt/dagster/dagster_home",
        "instance_config_map": f"{RELEASE}-dagster-instance",
        "postgres_password_secret": "dagster-postgresql",
    }
    if stock.get("imagePullSecrets"):
        cfg["image_pull_secrets"] = stock["imagePullSecrets"]
    cfg["run_k8s_config"] = {
        "pod_template_spec_metadata": {"labels": labels},
        "container_config": container,
        "pod_spec_config": pod,
    }
    # the two documented restrictions: nothing a run tag may set
    cfg["only_allow_user_defined_k8s_config_fields"] = {}
    cfg["only_allow_user_defined_env_vars"] = []
    overlay = {
        "dagster": {
            "runLauncher": {
                "type": "CustomRunLauncher",
                "config": {"customRunLauncher": {"module": "dagster_k8s", "class": "K8sRunLauncher", "config": cfg}},
            },
            "dagster-user-deployments": {
                "deployments": [{**copy.deepcopy(dep), "includeConfigInLaunchedRuns": {"enabled": False}}],
            },
        }
    }
    body = yaml.safe_dump(overlay, sort_keys=False, width=100, default_flow_style=False)
    return HEADER.format() + body


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", action="append", default=[])
    ap.add_argument("--values", default=VALUES, help="values.yaml to read (tests)")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    text = generate([os.path.join(ROOT, p) if not os.path.isabs(p) else p for p in a.profile], a.values)
    if a.write:
        open(OUT, "w").write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
