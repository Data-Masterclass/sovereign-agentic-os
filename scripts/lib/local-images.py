"""The images a local (kind) install builds from this checkout, and the values that point the chart at them.

    local-images.py plan [-f values.local.yaml ...] [--context KEY=DIR ...]
        One tab-separated line per image: key, ref, dockerfile ('-' = <context>/Dockerfile), context, target.
        scripts/os and tests/e2e/kind/up.sh build exactly these refs and `kind load` them.
    local-images.py gen-values [--write] [--check]
        The generated `dagster-user-deployments` block of values.local.yaml (see below).
    local-images.py hosts
        The network destinations the builds and the chart dependencies need, DERIVED from the Dockerfiles in
        IMAGES and Chart.yaml (host, then the images/steps that need it). docs/ops/install.md lists them;
        scripts/tests/local-images.test.sh fails when a derived host is missing there.

Why: the chart pins our own images by registry DIGEST in private ghcr.io packages (Dagster, LiteLLM, Langfuse,
the git sidecars). A pilot install on a server without that registry credential ended in ImagePullBackOff
(Nov 2026): a local build cannot carry a registry digest, values.local.yaml did not override the Dagster and git
images, and the git images were not in scripts/os's build list. So:
  - every image the local profile needs that is not public is listed in IMAGES and built here;
  - values.local.yaml names a LOCAL tag for each (no digest); `plan` refuses a ref that still carries a digest;
  - scripts/tests/local-images.test.sh renders the local profile and fails when an image in it is neither
    built here nor public.

The Dagster code location lives in a LIST (`dagster.dagster-user-deployments.deployments`), and Helm replaces lists
instead of merging them, so values.local.yaml must restate the whole `sovereign` entry to change its image. That
copy is DERIVED from values.yaml (same pattern as scripts/gen-dagster-launcher-lockdown.py): `gen-values --write`
rewrites the block between the markers, and the test fails when the checked-in block differs from this output.
"""
from __future__ import annotations

import argparse
import copy
import os
import sys

import yaml

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
VALUES = os.path.join(ROOT, "charts", "sovereign-agentic-os", "values.yaml")
LOCAL = os.path.join(ROOT, "values.local.yaml")
LOCATION = "sovereign"
BEGIN = "  # >>> GENERATED by scripts/lib/local-images.py gen-values"
END = "  # <<< GENERATED (local-images.py)"

# key, values path of the image map, dockerfile ('-' = <context>/Dockerfile), build context, docker --target
IMAGES = [
    ("osUI", "osUI.image", "images/base/os-ui/Dockerfile", ".", ""),
    ("egressProxy", "egressProxy.image", "-", "images/base/egress-proxy", ""),
    ("webFetch", "webFetch.image", "-", "images/base/web-fetch", ""),
    ("mockModel", "mockModel.image", "-", "images/base/mock-model", ""),
    ("gitDaemon", "osUI.dataProjectGit.gitDaemon.image", "-", "images/base/git-daemon", ""),
    ("gitHttp", "osUI.dataProjectGit.gitHttp.image", "-", "images/base/git-http", ""),
    ("dagster", "dagster.dagsterWebserver.image", "images/extensions/dagster/Dockerfile", "images/extensions", ""),
    ("dbt", "dbt.image", "-", "images/extensions/dbt", ""),
    ("dataRunner", "dataRunner.image", "-", "images/extensions/data-runner", ""),
    ("queryTool", "queryTool.image", "-", "images/extensions/query-tool", ""),
    ("docling", "docling.image", "-", "images/extensions/docling", ""),
    ("litellm", "litellm.image", "-", "images/extensions/litellm-oss", ""),
    ("langfuseWeb", "langfuse.langfuse.web.image", "-", "images/extensions/langfuse-oss", "web"),
    ("langfuseWorker", "langfuse.langfuse.worker.image", "-", "images/extensions/langfuse-oss", "worker"),
]


def merge(a, b):
    """Helm's values merge: maps recurse, everything else (lists included) is replaced."""
    if isinstance(a, dict) and isinstance(b, dict):
        out = dict(a)
        for k, v in b.items():
            out[k] = merge(a[k], v) if k in a else copy.deepcopy(v)
        return out
    return copy.deepcopy(b)


def load(files: list[str]) -> dict:
    v = yaml.safe_load(open(VALUES))
    for f in files:
        v = merge(v, yaml.safe_load(open(f)) or {})
    return v


def get(v: dict, path: str):
    for p in path.split("."):
        v = (v or {}).get(p)
    return v


def ref_of(key: str, img: dict) -> str:
    if not isinstance(img, dict) or not img.get("repository") or not img.get("tag"):
        raise SystemExit(f"local-images: {key}: no repository/tag in the merged values ({img!r})")
    tag = str(img["tag"])
    if "@" in tag or (img.get("digest") and not img.get("localBuild")):
        raise SystemExit(
            f"local-images: {key}: {img['repository']}:{tag} is pinned by registry digest; a local build cannot "
            f"carry it. Name a local tag (and digest: \"\") for it in values.local.yaml."
        )
    return f"{img['repository']}:{tag}"


def plan(files: list[str], contexts: dict[str, str]) -> list[tuple[str, str, str, str, str]]:
    v = load(files)
    rows = []
    for key, path, dockerfile, ctx, target in IMAGES:
        if key in contexts:
            ctx, dockerfile = contexts[key], "-"
        rows.append((key, ref_of(key, get(v, path)), dockerfile, ctx, target))
    return rows


def generated_block(values: str = VALUES, local: str = LOCAL) -> str:
    chart = yaml.safe_load(open(values))
    lv = yaml.safe_load(open(local)) or {}
    img = get(lv, "dagster.dagsterWebserver.image") or {}
    local_ref = ref_of("dagster", img)
    dep = next(d for d in chart["dagster"]["dagster-user-deployments"]["deployments"] if d["name"] == LOCATION)
    pinned = dep["image"]
    pinned_refs = {f"{pinned['repository']}@{pinned.get('digest')}", f"{pinned['repository']}:{pinned['tag']}@{pinned.get('digest')}",
                   f"{pinned['repository']}:{pinned['tag']}"}
    dep = copy.deepcopy(dep)
    dep["image"] = {"repository": img["repository"], "tag": str(img["tag"]), "pullPolicy": "IfNotPresent"}
    for c in dep.get("sidecarContainers") or []:
        if c.get("image") not in pinned_refs:
            raise SystemExit(f"local-images: sidecar {c.get('name')} runs {c.get('image')}, not the code location's image; "
                             "add it to IMAGES and map it here")
        c["image"] = local_ref
    body = yaml.safe_dump({"dagster-user-deployments": {"deployments": [dep]}}, sort_keys=False, width=100,
                          default_flow_style=False)
    lines = [
        BEGIN,
        "  # from charts/sovereign-agentic-os/values.yaml's `sovereign` code location, with the image (and the repo-sync",
        "  # sidecar's) pointed at the local build above. Do not edit by hand: change values.yaml, then run",
        "  #   python3 scripts/lib/local-images.py gen-values --write",
        "  # scripts/tests/local-images.test.sh fails CI when this block differs from the generator.",
    ]
    lines += ["  " + l if l else l for l in body.rstrip("\n").split("\n")]
    lines.append(END)
    return "\n".join(lines) + "\n"


def splice(text: str, block: str) -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit(f"local-images: markers not found in values.local.yaml ({BEGIN.strip()!r} … {END.strip()!r})")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + block + (tail.split("\n", 1)[1] if "\n" in tail else "")


# What a build step fetches from, by the tool that fetches it. The Dockerfile names the tool, not the host.
TOOL_HOSTS = [
    (r"\bapk add\b", ["dl-cdn.alpinelinux.org"]),
    (r"\bapt-get (update|install)\b", ["deb.debian.org", "security.debian.org"]),
    (r"\bpip install\b", ["pypi.org", "files.pythonhosted.org"]),
    (r"\b(npm ci|npm install|pnpm install)\b", ["registry.npmjs.org"]),
    (r"\bgo install\b", ["proxy.golang.org", "sum.golang.org"]),
    (r"\bsnapshot_download\(", ["huggingface.co", "*.hf.co"]),
    (r"\bprisma (generate|py fetch)\b|prisma-cli|/prisma/", ["binaries.prisma.sh"]),
]


def registry_of(image: str) -> str:
    first = image.split("/", 1)[0]
    if "/" in image and ("." in first or ":" in first or first == "localhost"):
        return "registry-1.docker.io" if first == "docker.io" else first
    return "registry-1.docker.io"


def hosts() -> dict[str, set[str]]:
    import re
    out: dict[str, set[str]] = {}
    add = lambda h, who: out.setdefault(h, set()).add(who)  # noqa: E731
    for key, _path, dockerfile, ctx, _t in IMAGES:
        path = os.path.join(ROOT, ctx, "Dockerfile") if dockerfile == "-" else os.path.join(ROOT, dockerfile)
        src = "\n".join(l for l in open(path).read().splitlines() if not l.lstrip().startswith("#"))
        args = dict(re.findall(r"^ARG\s+(\w+)=(\S+)", src, re.M))
        for m in re.findall(r"^FROM\s+(?:--\S+\s+)*(\S+)", src, re.M):
            m = re.sub(r"\$\{(\w+)\}", lambda g: args.get(g.group(1), ""), m)
            if any(c in m for c in ":/@"):  # an image reference, not a build-stage name or `scratch`
                add(registry_of(m), f"{key} (base image)")
        for line in src.splitlines():
            if "org.opencontainers." in line:  # image metadata, not a download
                continue
            for h in re.findall(r"https?://([A-Za-z0-9.-]+)", line):
                add(h, key)
        for rx, hs in TOOL_HOSTS:
            if re.search(rx, src):
                for h in hs:
                    add(h, key)
    chart = open(os.path.join(ROOT, "charts", "sovereign-agentic-os", "Chart.yaml")).read()
    for r in re.findall(r"^\s*repository:\s*[\"']?([a-z]+://[^\"'\s]+)", chart, re.M):
        add(r.split("://", 1)[1].split("/", 1)[0], "helm dependencies (Chart.yaml)")
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("plan")
    p.add_argument("-f", dest="files", action="append", default=[])
    p.add_argument("--context", action="append", default=[], help="KEY=DIR: build KEY from DIR/Dockerfile instead")
    g = sub.add_parser("gen-values")
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--values", default=VALUES)
    g.add_argument("--local", default=LOCAL)
    sub.add_parser("hosts")
    a = ap.parse_args()
    if a.cmd == "hosts":
        for h, who in sorted(hosts().items()):
            print(f"{h}\t{', '.join(sorted(who))}")
        return 0
    if a.cmd == "plan":
        ctx = dict(c.split("=", 1) for c in a.context)
        for row in plan([f if os.path.isabs(f) else os.path.join(ROOT, f) for f in a.files] or [LOCAL], ctx):
            print("\t".join(r or "-" for r in row))
        return 0
    text = open(a.local).read()
    new = splice(text, generated_block(a.values, a.local))
    if a.check:
        if new != text:
            print("local-images: values.local.yaml's generated block is stale: python3 scripts/lib/local-images.py gen-values --write",
                  file=sys.stderr)
            return 1
        return 0
    if a.write:
        open(a.local, "w").write(new)
    else:
        sys.stdout.write(generated_block(a.values, a.local))
    return 0


if __name__ == "__main__":
    sys.exit(main())
