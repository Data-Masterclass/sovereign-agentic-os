"""rotation-files.py — the private overlay files of scripts/ops/rotate-secrets.sh.

  rotation-files.py write <dir> <stamp>   < JSON   writes the overlays + state, prints their paths
  rotation-files.py kind <overlay>                prints: step1 | final | rollback | rollback-step1
  rotation-files.py state <overlay>               prints the state file next to an overlay
  rotation-files.py get <yaml file> <dotted.path> prints one value ("" when absent) — for a shell variable

Values arrive on stdin (never argv) and are written only to files created with mode 600. The state
file holds no secret: the path, the cluster identity, counts, model names and sha256 prefixes.

Overlays written for one rotation <stamp>:
  rotation-<stamp>.step1.yaml           re-key path only: LiteLLM re-encrypts every stored value
                                        from the old master key to S (LITELLM_MIGRATE_FROM_MASTER_KEY)
  rotation-<stamp>.yaml                 the final values
  rotation-<stamp>.rollback-step1.yaml  re-key path only: back from step 1 (re-encrypts S -> old)
  rotation-<stamp>.rollback.yaml        back from the final values (the salt key stays)
"""
import hashlib
import json
import os
import sys

import yaml

MIGRATE = "LITELLM_MIGRATE_FROM_MASTER_KEY"


def h16(value):
    return hashlib.sha256((value or "").encode()).hexdigest()[:16]


def dump(path, tree, title):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(f"# {title} — PRIVATE, never commit. Generated by scripts/ops/rotate-secrets.sh.\n")
        yaml.safe_dump(tree, f, sort_keys=False, default_flow_style=False)


def others(v):
    """The secrets that change in place in the final step (absent keys are left alone)."""
    out = {}
    init = {}
    if v.get("pk"):
        init.update({"publicKey": v["pk"], "secretKey": v["sk"]})
    # Langfuse core secrets: langfuseInit.{salt,nextauthSecret,encryptionKey} (templates/base/langfuse/core-secrets.yaml).
    init.update({k: v[f"lf_{k}"] for k in ("salt", "nextauthSecret", "encryptionKey") if v.get(f"lf_{k}")})
    if init:
        out["langfuseInit"] = init
    if v.get("agent_token"):
        out["agentRuntime"] = {"token": v["agent_token"]}
    if v.get("ui_password"):
        out["litellmUI"] = {"password": v["ui_password"]}
    return out


def write(directory, stamp):
    d = json.load(sys.stdin)
    path, old, new = d["path"], d["old"], d["new"]
    base = os.path.join(directory, f"rotation-{stamp}")
    files = {}

    final = {"litellmMasterKey": new["master"], "litellmSaltKey": {"value": new["salt"]}}
    if path == "rekey":
        # Step 1: no salt yet, the master key becomes S, LiteLLM re-encrypts old -> S at boot.
        step1 = {"litellmMasterKey": new["salt"], "litellm": {"envVars": {MIGRATE: old["master"]}}}
        dump(base + ".step1.yaml", step1, f"rotation {stamp}, step 1 of 2 (re-key)")
        files["step1"] = base + ".step1.yaml"
        # Step 2 empties the migration variable. A null cannot delete a key that an earlier values
        # file set (deploy.sh layers the overlay over the release values), and the subchart renders
        # every envVars key, so the variable stays with an EMPTY value: LiteLLM then does nothing
        # (with a salt key set, and with an empty key there is nothing encrypted under it).
        final["litellm"] = {"envVars": {MIGRATE: ""}}
        back1 = {"litellmMasterKey": old["master"], "litellm": {"envVars": {MIGRATE: new["salt"]}}}
        dump(base + ".rollback-step1.yaml", back1, f"rollback of step 1, rotation {stamp}")
        files["rollback-step1"] = base + ".rollback-step1.yaml"
    final.update(others(new))
    dump(base + ".yaml", final, f"rotation {stamp} ({path}), final values")
    files["final"] = base + ".yaml"

    # Rollback of the final values: previous master key and in-place secrets; the salt key STAYS
    # (Helm cannot remove it from the live Secret, and the stored values are encrypted with it).
    back = {"litellmMasterKey": old["master"], "litellmSaltKey": {"value": new["salt"]}}
    back.update(others(old))
    dump(base + ".rollback.yaml", back, f"rollback of rotation {stamp}")
    files["rollback"] = base + ".rollback.yaml"

    state = {
        "path": path,
        "cluster": d["cluster"],
        "counts_before": d["counts"],
        "db_models": d.get("db_models", []),
        "langfuse_encrypted": d.get("langfuse_encrypted", {}),
        "rotate_langfuse_encryption_key": bool(new.get("lf_encryptionKey")),
        "sha256_16": {
            "old_master": h16(old["master"]),
            "step1_master": h16(new["salt"]) if path == "rekey" else "",
            "new_master": h16(new["master"]),
            "salt": h16(new["salt"]),
            "old_langfuse_pk": h16(old.get("pk")),
            "new_langfuse_pk": h16(new.get("pk")),
        },
        "files": files,
    }
    fd = os.open(base + ".state.json", os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as f:
        json.dump(state, f, indent=1)
    for kind, p in files.items():
        print(f"{kind}\t{p}")
    print(f"state\t{base}.state.json")


def kind(overlay):
    name = os.path.basename(overlay)
    for suffix in ("rollback-step1", "rollback", "step1"):
        if name.endswith(f".{suffix}.yaml"):
            return suffix
    return "final"


def state_of(overlay):
    name = overlay
    k = kind(overlay)
    if k != "final":
        name = overlay[: -len(f".{k}.yaml")] + ".yaml"
    return name[: -len(".yaml")] + ".state.json"


def get(path, dotted):
    with open(path) as f:
        node = yaml.safe_load(f) or {}
    for part in dotted.split("."):
        node = node.get(part) if isinstance(node, dict) else None
    print("" if node is None else node)


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "write":
        write(sys.argv[2], sys.argv[3])
    elif cmd == "kind":
        print(kind(sys.argv[2]))
    elif cmd == "state":
        print(state_of(sys.argv[2]))
    elif cmd == "get":
        get(sys.argv[2], sys.argv[3])
    else:
        sys.exit(f"unknown command {cmd}")
